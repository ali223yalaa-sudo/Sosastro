                .fillMaxWidth()
                .padding(horizontal = Size20dp, vertical = 24.dp),
        ) {
            Text(
                text = stringRes(R.string.profile_canvas_use_profile_icon),
                style = MaterialTheme.typography.bodyLarge,
                color = Color.Gray,
            )
        }
    }
}
